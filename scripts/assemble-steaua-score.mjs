#!/usr/bin/env node
/** Assemble the authored score against measured v3 durations; no audio synthesis. */
import {promises as fs} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=JSON.parse(await fs.readFile(path.join(root,'assets/scenarios/age-5-10/steaua-authoring.json'),'utf8'));
const stage=path.join(root,'runs/steaua-production/staged');
const manifest=JSON.parse(await fs.readFile(path.join(stage,'scenario/manifest.json'),'utf8'));
// Farewells bridge the cut to the next world. Instructions finish before activities open.
const times={R07:1,R08:13.2,R09:27.1,R10:37,R11:45.2,R12:-9,R13:5,R13a:17,R14:28,
 R14a:59,R14b:72,R15:83,R16:93.2,R17:115,R18:129.5,R19:129.5,R20:129.5,R21:139.7,
 R21a:150,R21b:169,R22:178,R23:190.5,R24:215,R25:229.5,R26:229.5,R27:229.5,R28:239.7,
 R28a:254,R28b:270,R29:295,R30:309.5,R31:337.5,R32:356.5,R33:356.5,R34:356.5,R34a:369.2,R35:382.7,
 R36:397,R37:453.5,R38:510,R39:527,R40:557,R40a:599,R41:613,R42:623,R42a:633,R43:645.5,R44:663,
 R45:2,R46:15,R47:15,R48:15,R49:30,R50:46,R51:62};
const timing={preshowDurationSec:60,epilogueDurationSec:75,videoDurationSec:678.05,stageWindows:[[106,129],[205,229],[323.5,355.5]],musicSilence:{phase:'play',startSec:368.9,endSec:382.2},ignitionSec:356.5,questionSec:369.2,cometSec:382.7,revelationSec:633};
const dialogue={...source.dialogue,title:'Steaua Omenirii',status:'integrated-author-revision',productionReady:false,audioStatus:'produced-eleven-v3',timingStatus:'measured-v3-aligned-to-film',
 sourceDocument:source.sourceDocument,sourceSha256:source.sourceSha256,timing};
dialogue.cues=dialogue.cues.map(c=>({...c,at:times[c.authorRef]}));
const report=[];
for(const c of dialogue.cues){
 const clip=manifest.clips[c.id];if(!clip||clip.text!==c.text.ro||clip.modelId!=='eleven_v3')throw Error('Generated voice mismatch: '+c.id);
 const end=c.phase==='preshow'?60:c.phase==='epilogue'?75:678.05;
 const next=Math.min(end,...dialogue.cues.filter(n=>n.phase===c.phase&&n.at>c.at).map(n=>n.at));
 c.maxDurationSec=Number((next-c.at).toFixed(3));
 const gap=Number((next-c.at-clip.durationMs/1000).toFixed(3));
 if(!Number.isFinite(c.at)||gap<0.25)throw Error(`${c.authorRef}: overlap/insufficient gap ${gap}`);
 clip.slotBudgetMs=Math.round(c.maxDurationSec*1000);clip.overBudgetMs=0;
 report.push({id:c.id,ref:c.authorRef,phase:c.phase,at:c.at,durationSec:clip.durationMs/1000,next,gapSec:gap,condition:c.condition});
}
for(const [ref,window] of [['R16',timing.stageWindows[0]],['R23',timing.stageWindows[1]],['R30',timing.stageWindows[2]]]){
 const c=dialogue.cues.find(c=>c.authorRef===ref);if(c.at+manifest.clips[c.id].durationMs/1000>window[0])throw Error('Instruction overlaps activity start: '+ref);
}
const order={preshow:0,play:1,epilogue:2};dialogue.cues.sort((a,b)=>order[a.phase]-order[b.phase]||a.at-b.at);
await fs.writeFile(path.join(stage,'dialogue.ro.draft.json'),JSON.stringify(dialogue,null,2)+'\n');
await fs.writeFile(path.join(stage,'scenario/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await fs.writeFile(path.join(stage,'timing-report.json'),JSON.stringify({timing,cues:report,allBranchesHaveRoom:true,audioTempo:1,filmUnchanged:true,minimumGapSec:Math.min(...report.map(c=>c.gapSec))},null,2)+'\n');
await fs.writeFile(path.join(root,'src/shared/star-score.ts'),'/** Steaua Omenirii: measured Eleven v3 score, generated by assemble-steaua-score.mjs. */\nexport const STAR_SCORE = '+JSON.stringify(timing,null,2)+' as const;\n');
console.log(JSON.stringify({cues:report.length,minimumGapSec:Math.min(...report.map(c=>c.gapSec)),timing}));
